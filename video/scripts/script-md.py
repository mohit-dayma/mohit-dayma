"""Write script/part-1.md from the narration and the measured voiceover timings.

The narration text lives in src/part1/narration.json (the source of truth for
the voiceover, the captions and the scene cues). Run after scripts/tts.py:

  python3 scripts/script-md.py
"""

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FPS = 30
# Keep in sync with src/part1/timeline.ts.
INTRO_LEAD, CHAPTER_LEAD, TAIL, OUTRO_TAIL = 90, 48, 12, 105

NOTES = {
    "intro": "Title card, then the hook. A cycle counter climbs while the CPU waits. The paper card, then the five-part series list.",
    "latency": "Illustrative CPU vs memory speed curves. Latency ladder (Pentium M, Drepper 2007 §3.2), then the 'typical today' bars. Pipeline timeline for the hiding aside.",
    "ram": "SRAM (6 transistors) and DRAM (1 transistor + capacitor) cards; the capacitor visibly leaks and is refreshed. The four costs reveal one by one.",
    "dram": "A DRAM bank: rows, row buffer, activation, column reads, precharge. Cost table for module timing 2-3-2 (CL / tRCD+CL / tRP+tRCD+CL). Deep Dive aside: 11:1 core/bus clock ratio. Since-2007 note.",
    "locality": "Temporal and spatial locality animations. The 200- vs 15-cycle worked example with animated bars (2,000,000 vs 168,500 cycles, 91.5%). 4 MB vs 4 GB drawn to scale.",
    "hierarchy": "Two cores with hardware threads, L1d/L1i, L2 (shared, then split into private L2s for 'today'), L3, main memory. Inclusive vs exclusive.",
    "lines": "A 64-byte line loads when one byte is needed. A 32-bit address split into tag / set / offset with cache-model splitAddress for the paper's 4 MB 8-way cache.",
    "assoc": "Fully associative, direct-mapped and 2-way layouts of the same 8 lines, with the slots an incoming line may use. LRU eviction in a 4-way set (cache-model simulate).",
    "sim": "The blog simulator, replayed with cache-model: sequential scan, reuse, and conflicting arrays in direct-mapped, 2-way and 4-way. Then the paper's gcc results (§3.3.1).",
    "writes": "Write-through vs write-back counters on a one-line cache (cache-model). Writeback counts from the conflicting-arrays run. Write-combining, uncacheable, coherence rules.",
    "addresses": "Virtual -> translation -> physical. The paper's 2007 answer. VIPT: the 32 KB 8-way L1d's set and offset fit the 12-bit page offset.",
    "changed": "2007 vs today table.",
    "remember": "Seven takeaways.",
    "outro": "Next: Part 2. End card with mohitd.com/blog and the Drepper (2007) credit.",
}


def ts(seconds: float) -> str:
    return f"{int(seconds // 60)}:{seconds % 60:04.1f}"


def main() -> None:
    narration = json.loads((ROOT / "src/part1/narration.json").read_text())
    timings = json.loads((ROOT / "src/part1/timings.json").read_text())["scenes"]
    out = [
        "# How CPU Caches Work: Memory Series, Part 1 (video script)",
        "",
        "Spoken adaptation of `content/blog/how-cpu-caches-work.mdx`. Generated by",
        "`scripts/script-md.py` from `src/part1/narration.json` (edit that file, not this",
        "one) and the voiceover timings in `src/part1/timings.json`. Times are positions",
        "in the final video. Each line is one caption.",
        "",
    ]
    start = 0
    chapter = 0
    rows = []
    for scene in narration["scenes"]:
        t = timings[scene["id"]]
        lead = INTRO_LEAD if scene["id"] == "intro" else (CHAPTER_LEAD if scene["chapter"] else 0)
        tail = OUTRO_TAIL if scene["id"] == "outro" else TAIL
        frames = lead + math.ceil(t["duration"] * FPS) + tail
        title = scene["chapter"] or ("Intro" if scene["id"] == "intro" else "Outro")
        if scene["chapter"]:
            chapter += 1
            title = f"{chapter:02d}. {title}"
        rows.append((title, start / FPS, frames / FPS))
        out += [f"## {title}", "", f"**{ts(start / FPS)} – {ts((start + frames) / FPS)}** ({frames / FPS:.0f} s)", ""]
        out += [f"_On screen:_ {NOTES[scene['id']]}", ""]
        if lead:
            out += [f"- `{ts(start / FPS)}` _({'title' if scene['id'] == 'intro' else 'chapter'} card, no narration)_"]
        for seg, st in zip(scene["segments"], t["segments"]):
            at = (start + lead + round(st["start"] * FPS)) / FPS
            out.append(f"- `{ts(at)}` {seg['text']}")
        out.append("")
        start += frames
    out[7:7] = ["| Scene | Start | Length |", "| --- | --- | --- |"] + [
        f"| {t} | {ts(s)} | {d:.0f} s |" for t, s, d in rows
    ] + [f"| **Total** | | **{ts(start / FPS)}** |", ""]
    (ROOT / "script/part-1.md").parent.mkdir(exist_ok=True)
    (ROOT / "script/part-1.md").write_text("\n".join(out) + "\n")
    print(f"total {ts(start / FPS)}")


if __name__ == "__main__":
    main()
